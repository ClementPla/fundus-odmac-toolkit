"""Write the benchmark table of the README from benchmarks/results.jsonl.

Replaces everything between the BENCHMARK:START and BENCHMARK:END markers.
"""

import json
import re
from pathlib import Path

ROOT = Path(__file__).parent
README = ROOT.parent / "README.md"

ARCH_NAMES = {"unet": "UNet", "unetplusplus": "UNet++"}
# (benchmark key, column header, higher is better, unit)
COLUMNS = [
    ("idrid_od_iou", "IDRiD OD IoU", True, "%"),
    ("riga_magrabia_od_iou", "RIGA-Magrabia OD IoU", True, "%"),
    ("riga_messidor_od_iou", "RIGA-MESSIDOR OD IoU", True, "%"),
    ("idrid_od_distance", "IDRiD OD distance (px)", False, ""),
    ("idrid_fovea_distance", "IDRiD fovea distance (px)", False, ""),
]
MODEL_ORDER = [
    ("unet", "seresnet50"),
    ("unet", "mobilevitv2_100"),
    ("unet", "mobilenetv3_small_050"),
    ("unet", "maxvit_tiny_tf_512"),
    ("unet", "maxvit_small_tf_512"),
    ("unet", "maxvit_base_tf_512"),
    ("unetplusplus", "seresnet50"),
    ("unetplusplus", "mobilenetv3_small_050"),
]


def main():
    rows = [json.loads(line) for line in (ROOT / "results.jsonl").read_text().splitlines() if line]
    for r in rows:  # distances: mean over the images where the structure is detected
        if "value_detected" in r:
            r["value"] = r["value_detected"]
    res = {(r["arch"], r["encoder"], r["benchmark"]): r for r in rows}
    models = [m for m in MODEL_ORDER if any(k[:2] == m for k in res)]
    models += sorted({k[:2] for k in res} - set(models))

    best = {}
    for key, _, higher, _ in COLUMNS:
        values = [res[(*m, key)]["value"] for m in models if (*m, key) in res]
        best[key] = max(values) if higher else min(values)

    header = ["Architecture", "Encoder", *(c[1] for c in COLUMNS)]
    lines = ["| " + " | ".join(header) + " |", "|" + "|".join([":---:"] * len(header)) + "|"]
    for arch, encoder in models:
        cells = [ARCH_NAMES.get(arch, arch), encoder]
        for key, _, _, unit in COLUMNS:
            r = res.get((arch, encoder, key))
            if r is None:
                cells.append("-")
                continue
            cell = f"{r['value']:.2f}{unit}"
            if r["value"] == best[key]:
                cell = f"**{cell}**"
            if r.get("missed"):
                cell += f" ({r['missed']} undetected)"
            cells.append(cell)
        lines.append("| " + " | ".join(cells) + " |")

    n = {key: next(r["n"] for r in rows if r["benchmark"] == key) for key, *_ in COLUMNS}
    section = f"""<!-- BENCHMARK:START (generated by benchmarks/update_readme.py, do not edit by hand) -->
Weights `v2` (default). All models are evaluated without test-time augmentation by [`benchmarks/run_benchmarks.py`](benchmarks/run_benchmarks.py); raw results are in [`benchmarks/results.jsonl`](benchmarks/results.jsonl).

{chr(10).join(lines)}

- **OD IoU**: Jaccard index of the optic disc, accumulated over all pixels of the test set.
  IDRiD: segmentation challenge test set ({n['idrid_od_iou']} images).
  RIGA: majority vote of the 6 annotators (Magrabia: {n['riga_magrabia_od_iou']} images, MESSIDOR: {n['riga_messidor_od_iou']} images).
- **Distance**: mean Euclidean distance (pixels) between the centroid of the predicted structure and the ground-truth center,
  on the IDRiD localization challenge test set ({n['idrid_fovea_distance']} images), averaged over the images where the structure is detected;
  the number of images where it is not detected is given in parentheses. (`results.jsonl` also gives the mean over all images,
  using the most probable pixel when nothing is detected: it is dominated by these few failures.)
- Best result per column in bold. See the [official IDRiD leaderboard](https://idrid.grand-challenge.org/Leaderboard/) for comparison.
- *We did not use the IDRiD segmentation masks for training.*
<!-- BENCHMARK:END -->"""

    text = README.read_text()
    pattern = re.compile(r"<!-- BENCHMARK:START.*?<!-- BENCHMARK:END -->", re.S)
    if not pattern.search(text):
        raise SystemExit("Benchmark markers not found in README.md")
    README.write_text(pattern.sub(lambda _: section, text))
    print(section)


if __name__ == "__main__":
    main()
